// Возвращает миксины для Alpine x-data: редактор + emoji picker + drag-and-drop upload.
function baseEditor(initialDescription) {
  const descForEditor = (initialDescription || '').replace(/\n/g, '<br>');
  return {
    description: descForEditor,
    initialDescription: descForEditor,
    uploading: false,
    uploadError: '',
    emojiOpen: false,
    emojiTab: 'smileys',
    emojiSearch: '',
    visibleEmoji: [],
    emojiCategories: EMOJI_CATEGORIES,
    emojiData: EMOJI_DATA,
    init() {
      this.filterEmoji();
    },
    syncDescription(e) {
      this.description = e.target.innerHTML;
    },
    exec(cmd) {
      document.execCommand(cmd, false, null);
      this.$refs.editor.focus();
      this.description = this.$refs.editor.innerHTML;
    },
    addLink() {
      const url = prompt('URL ссылки:');
      if (url) {
        document.execCommand('createLink', false, url);
        this.description = this.$refs.editor.innerHTML;
      }
    },
    wrapSpoiler() {
      const sel = window.getSelection();
      if (!sel || !sel.rangeCount) return;
      const range = sel.getRangeAt(0);
      const text = range.toString();
      if (!text) return;
      const span = document.createElement('tg-spoiler');
      span.textContent = text;
      range.deleteContents();
      range.insertNode(span);
      this.description = this.$refs.editor.innerHTML;
    },
    clearFormat() {
      document.execCommand('removeFormat', false, null);
      this.description = this.$refs.editor.innerHTML;
    },
    toggleEmoji() {
      this.emojiOpen = !this.emojiOpen;
      if (this.emojiOpen) this.filterEmoji();
    },
    filterEmoji() {
      const q = (this.emojiSearch || '').trim();
      if (q) {
        const all = Object.values(this.emojiData).flat();
        this.visibleEmoji = all.filter(e => e.includes(q));
      } else {
        this.visibleEmoji = this.emojiData[this.emojiTab] || [];
      }
    },
    insertEmoji(emoji) {
      const editor = this.$refs.editor;
      editor.focus();
      const sel = window.getSelection();
      if (sel && sel.rangeCount && editor.contains(sel.anchorNode)) {
        const range = sel.getRangeAt(0);
        range.deleteContents();
        range.insertNode(document.createTextNode(emoji));
        range.collapse(false);
        sel.removeAllRanges();
        sel.addRange(range);
      } else {
        editor.innerHTML += emoji;
      }
      this.description = editor.innerHTML;
    },
    async onPick(e) {
      const f = e.target.files[0];
      if (f) await this.upload(f);
    },
    async onDrop(e) {
      const f = e.dataTransfer.files[0];
      if (f) await this.upload(f);
    },
    async upload(file) {
      this.uploadError = '';
      this.uploading = true;
      const fd = new FormData();
      fd.append('file', file);
      try {
        const r = await fetch('/upload', {method: 'POST', body: fd});
        if (!r.ok) {
          const j = await r.json().catch(() => ({}));
          this.uploadError = j.detail || 'Ошибка загрузки';
        } else {
          const j = await r.json();
          this.image = j.filename;
        }
      } catch (e) {
        this.uploadError = 'Сеть недоступна';
      } finally {
        this.uploading = false;
      }
    },
  };
}
